// The picture of one product idea or project: a picture generated for THAT exact idea (from its
// own materials, look and build steps — see server/ai/images.js), a skeleton while it is being
// made, or a neutral "no picture" panel. No stock photos and no generic category drawings: a
// picture that isn't of this product would be misleading.
import { useEffect, useRef, useState } from 'react';
import { ImageOff } from 'lucide-react';
import { api } from '../api/client.js';
import { resolveKind, resolveMaterial } from '../../shared/productKind.js';

export { resolveKind, resolveMaterial };

// Saved projects without a picture ask the server for one (generated once, then stored with the
// project) — at most two at a time across the page.
const queue = { active: 0, waiting: [], done: new Map(), off: null };
function requestProjectImage(id) {
  // Pictures are switched off or unavailable on this server: stop asking (no request at all).
  if (queue.off) return Promise.reject(queue.off);
  if (queue.done.has(id)) return queue.done.get(id);
  const p = new Promise((resolve, reject) => {
    const run = () => {
      queue.active += 1;
      api.post(`/projects/${id}/image`).then(resolve, reject).finally(() => {
        queue.active -= 1;
        queue.waiting.shift()?.();
      });
    };
    if (queue.active < 2) run();
    else queue.waiting.push(run);
  });
  queue.done.set(id, p);
  p.catch((err) => {
    queue.done.delete(id); // a later visit may try again…
    if (/^images_(off|needs_billing|model_unavailable|daily_limit|unconfigured)$/.test(err?.code || '')) queue.off = err; // …unless pictures are off for this server
  });
  return p;
}

/**
 * @param idea          the idea or project (name, …); a stored picture is read from idea.image
 *                      (or idea.idea.image for a project row)
 * @param image         a picture generated for this idea ({src, model}) by the caller
 * @param imageLoading  the caller is generating the picture — a skeleton is shown meanwhile
 * @param project       a saved project ({id, isExample}): its picture is generated when it comes into view
 * @param caption       show the "AI-generated preview" label
 */
export function ProductPreview({ idea, image, imageLoading = false, caption = true, className = '', project }) {
  const ref = useRef(null);
  const [broken, setBroken] = useState(false);
  const [own, setOwn] = useState(null); // { loading } | { src, model } | { error }
  const stored = idea?.image || idea?.idea?.image || null;
  const gen = broken ? null : image?.src ? image : stored?.src ? stored : own?.src ? own : null;
  const name = idea?.name || 'this product';

  useEffect(() => {
    const el = ref.current;
    if (!el || !project?.id || project.isExample || gen || own) return undefined;
    const start = () => {
      setOwn({ loading: true });
      requestProjectImage(project.id).then((r) => setOwn({ src: r.src, model: r.model }), (e) => setOwn({ error: e.message }));
    };
    if (typeof IntersectionObserver === 'undefined') {
      start();
      return undefined;
    }
    const io = new IntersectionObserver((entries) => {
      if (entries.some((e) => e.isIntersecting)) {
        io.disconnect();
        start();
      }
    }, { rootMargin: '200px' });
    io.observe(el);
    return () => io.disconnect();
  }, [project?.id, project?.isExample, Boolean(gen)]); // eslint-disable-line react-hooks/exhaustive-deps

  if (gen) {
    // Generated from this idea's own description — a preview, not a photo of a real build.
    return (
      <figure ref={ref} className={`product-preview is-photo is-generated ${className}`}>
        <img src={gen.src} alt={`AI-generated preview of ${name}`} decoding="async" onError={() => setBroken(true)} />
        {caption && <figcaption title={`Generated by Google ${gen.model || 'Gemini'} from this idea's materials and build steps — not a photo of a real build`}>AI-generated preview</figcaption>}
      </figure>
    );
  }
  if (imageLoading || own?.loading) {
    return (
      <figure ref={ref} className={`product-preview is-loading ${className}`} aria-busy="true" aria-label={`Creating a picture of ${name}`}>
        <div className="pp-skeleton" />
        {caption && <figcaption className="is-loading"><span className="spinner" style={{ width: 9, height: 9 }} />Creating picture…</figcaption>}
      </figure>
    );
  }
  return (
    <figure ref={ref} className={`product-preview is-empty ${className}`} role="img" aria-label={`No picture of ${name}`}>
      <div className="pp-empty">
        <ImageOff size={22} aria-hidden="true" />
        {caption && <span>{own?.error || broken ? 'Picture unavailable' : 'No picture yet'}</span>}
      </div>
    </figure>
  );
}
